/**
 * Build src/packs/ak-park.ts from the research data in data/ak-pack.
 *
 *   npx tsx scripts/build-ak-pack.ts
 *
 * Reads ak-ledger.json, ak-pack.json, queries-draft.json and queries-user.json.
 * Fails (exit 1, nothing written) when any pack item is missing from the
 * ledger, not open, not sufficiently sourced, or has no area. Never drops an
 * item on its own.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import type { LabeledQuery, Pack, PackItem } from '../src/packs/types';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DATA_DIR = join(ROOT, 'data', 'ak-pack');
const OUT_FILE = join(ROOT, 'src', 'packs', 'ak-park.ts');

interface LedgerSource {
  tier: string;
}

interface LedgerEntry extends PackItem {
  status: string;
  confidence: string;
  sources: LedgerSource[];
}

interface PackList {
  packItemIds: string[];
  pendingAreaCorrection?: unknown;
}

interface RawQuery extends Omit<LabeledQuery, 'holdout'> {
  note: string;
}

function readJson<T>(file: string): T {
  return JSON.parse(readFileSync(join(DATA_DIR, file), 'utf8')) as T;
}

function fail(title: string, lines: string[]): never {
  console.error(`build-ak-pack: ${title}`);
  for (const line of lines) console.error(`  - ${line}`);
  console.error('Nothing written.');
  process.exit(1);
}

const ledger = readJson<LedgerEntry[]>('ak-ledger.json');
const packList = readJson<PackList>('ak-pack.json');
const draftQueries = readJson<RawQuery[]>('queries-draft.json');
const userQueries = readJson<RawQuery[]>('queries-user.json');

// --- Pack-level guards -------------------------------------------------------

const pending = packList.pendingAreaCorrection;
if (pending !== undefined && !(Array.isArray(pending) && pending.length === 0)) {
  fail('ak-pack.json still lists pendingAreaCorrection; resolve it first:', [JSON.stringify(pending)]);
}

// --- Items -------------------------------------------------------------------

const byId = new Map(ledger.map((entry) => [entry.id, entry]));
const offenders: string[] = [];
const items: PackItem[] = [];

for (const id of packList.packItemIds) {
  const entry = byId.get(id);
  if (!entry) {
    offenders.push(`${id}: not in ak-ledger.json`);
    continue;
  }
  const userConfirmed = entry.sources.some((source) => source.tier === 'user-confirmed');
  const reasons: string[] = [];
  if (entry.status !== 'open') reasons.push(`status "${entry.status}" (needs "open")`);
  if (entry.confidence !== 'two-sources' && !userConfirmed) {
    reasons.push(`confidence "${entry.confidence}" and no user-confirmed source`);
  }
  if (!entry.area || entry.area.trim() === '') reasons.push('empty area');
  if (reasons.length > 0) {
    offenders.push(`${id}: ${reasons.join('; ')}`);
    continue;
  }

  // PackItem fields only: sources, notes, confidence, status and dates stay in the ledger.
  items.push({
    id: entry.id,
    name: entry.name,
    kind: entry.kind,
    area: entry.area,
    aliases: entry.aliases,
    species: entry.species,
    description: entry.description,
    attributes: entry.attributes,
    hoursNote: entry.hoursNote,
  });
}

if (offenders.length > 0) {
  fail(`${offenders.length} pack item(s) are not eligible:`, offenders);
}

// --- Queries -----------------------------------------------------------------

const seenQueryIds = new Map<string, string>();
const collisions: string[] = [];
const queries: LabeledQuery[] = [];

for (const [file, list] of [
  ['queries-draft.json', draftQueries],
  ['queries-user.json', userQueries],
] as const) {
  for (const raw of list) {
    const previous = seenQueryIds.get(raw.id);
    if (previous) collisions.push(`${raw.id}: in both ${previous} and ${file}`);
    seenQueryIds.set(raw.id, file);

    const query: LabeledQuery = {
      id: raw.id,
      text: raw.text,
      category: raw.category,
      expectedItemIds: raw.expectedItemIds,
      shouldDecline: raw.shouldDecline,
    };
    if (raw.note) query.note = raw.note;
    if (raw.note === 'holdout') query.holdout = true;
    queries.push(query);
  }
}

if (collisions.length > 0) {
  fail(`${collisions.length} query id collision(s):`, collisions);
}

// --- Write -------------------------------------------------------------------

const byIdOrder = (a: { id: string }, b: { id: string }) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0);
items.sort(byIdOrder);
queries.sort(byIdOrder);

const pack: Pack = {
  key: 'ak-park',
  displayName: 'Animal Kingdom',
  domainDescription:
    'An animal-themed park organized into themed areas, with rides, walking trails, animal habitats, dining, live shows, and guest services.',
  items,
  queries,
};

const source = `/**
 * GENERATED by scripts/build-ak-pack.ts from data/ak-pack; do not edit by hand.
 */
import type { Pack } from './types';

export const akPark: Pack = ${JSON.stringify(pack, null, 2)};
`;

writeFileSync(OUT_FILE, source);
console.log(`Wrote ${OUT_FILE.slice(ROOT.length + 1)}: ${items.length} items, ${queries.length} queries`);
